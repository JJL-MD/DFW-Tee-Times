/**
 * Flatten seed into D1 INSERT payloads.
 * Returns { courses, courseProviders } with timestamps populated.
 */
/**
 * D1 row shape for `courses`. Matches the column names in
 * migrations/0001_init.sql (snake_case).
 */
export interface SeedCourseRow {
  id: string;
  name: string;
  city: string;
  state: string;
  lat: number;
  lon: number;
  default_provider: Provider;
  booking_window_days: number;
  booking_opens_at_local: string;
  timezone: string;
  created_at: number;
  updated_at: number;
}

export function buildSeedRows(now: number = Date.now()): {
  courses: SeedCourseRow[];
  courseProviders: CourseProvider[];
} {
  const courses: SeedCourseRow[] = DFW_COURSES.map((c) => ({
    id: c.id,
    name: c.name,
    city: c.city,
    state: c.state,
    lat: c.lat,
    lon: c.lon,
    default_provider: c.defaultProvider,
    booking_window_days: c.bookingWindowDays,
    booking_opens_at_local: c.bookingOpensAtLocal,
    timezone: c.timezone,
    created_at: now,
    updated_at: now,
  }));

  const courseProviders: CourseProvider[] = [];
  for (const c of DFW_COURSES) {
    for (const [provider, providerCourseId] of Object.entries(c.providerIds)) {
      if (!providerCourseId) continue;
      courseProviders.push({
        courseId: c.id,
        provider: provider as Provider,
        providerCourseId,
      });
    }
  }

  return { courses, courseProviders };
}